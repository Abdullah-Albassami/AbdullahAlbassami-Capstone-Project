import os
from pathlib import Path

from django.core.exceptions import ImproperlyConfigured

BASE_DIR = Path(__file__).resolve().parent.parent

SECRET_KEY = os.environ.get("DJANGO_SECRET_KEY", "").strip()
if len(SECRET_KEY) < 50 or SECRET_KEY.startswith("replace-"):
    raise ImproperlyConfigured(
        "Set DJANGO_SECRET_KEY to a locally generated random key of at least "
        "50 characters. See README.md. Do not commit the key."
    )

debug_value = os.environ.get("DJANGO_DEBUG", "true").strip().lower()
if debug_value not in {"true", "false", "1", "0"}:
    raise ImproperlyConfigured("DJANGO_DEBUG must be true, false, 1 or 0.")
DEBUG = debug_value in {"true", "1"}
ALLOWED_HOSTS = [
    host.strip()
    for host in os.environ.get(
        "DJANGO_ALLOWED_HOSTS", "localhost,127.0.0.1,[::1]"
    ).split(",")
    if host.strip()
]
if not ALLOWED_HOSTS or "*" in ALLOWED_HOSTS:
    raise ImproperlyConfigured("Set explicit hosts in DJANGO_ALLOWED_HOSTS; do not use '*'.")

